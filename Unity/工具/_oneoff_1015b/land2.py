def insert_after(text, anchor, rows, tag):
    lines = text.split("\n")
    hits = [i for i, L in enumerate(lines) if anchor in L]
    assert len(hits) == 1, "%s：锚点命中 %d 次" % (tag, len(hits))
    i = hits[0]
    for r in rows:
        assert r.count("|") == 3, "%s：新行竖线 %d（应 3）：%s" % (tag, r.count("|"), r[:60])
    lines[i + 1:i + 1] = rows
    return "\n".join(lines)


def del_line(text, anchor, tag):
    lines = text.split("\n")
    hits = [i for i, L in enumerate(lines) if anchor in L]
    assert len(hits) == 1, "%s：删行锚点命中 %d" % (tag, len(hits))
    del lines[hits[0]]
    return "\n".join(lines)


def append_to_row(text, row_anchor, frag, tag):
    lines = text.split("\n")
    hits = [i for i, L in enumerate(lines) if row_anchor in L]
    assert len(hits) == 1, "%s：行锚点命中 %d" % (tag, len(hits))
    i = hits[0]
    L = lines[i]
    assert L.rstrip().endswith("|"), "%s：该行不以 | 收尾" % tag
    assert L.count("|") in (3, 5), "%s：该行竖线 %d" % (tag, L.count("|"))
    j = L.rstrip().rfind("|")
    lines[i] = L[:j] + frag + L[j:]
    return "\n".join(lines)



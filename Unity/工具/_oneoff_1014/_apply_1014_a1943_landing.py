def patch(path, pairs, insert_after=None, insert_text=None):
    b = io.open(path, 'rb').read()
    assert b.count(b'\r\n') == 0, '%s must be LF' % path
    t = b.decode('utf-8')
    for old, new in pairs:
        n = t.count(old)
        assert n == 1, 'anchor hits=%d in %s :: %s' % (n, path, old[:70])
        t = t.replace(old, new)
    if insert_after:
        lines = t.split('\n')
        hits = [i for i, l in enumerate(lines) if insert_after in l]
        assert len(hits) == 1, 'marker hits=%d' % len(hits)
        i = hits[0]
        assert lines[i].startswith('| ') and lines[i].rstrip().endswith(' |'), lines[i][:80]
        lines[i + 1:i + 1] = [insert_text]
        t = '\n'.join(lines)
    assert '\x00' not in t and '\r\n' not in t
    io.open(path, 'wb').write(t.encode('utf-8'))
    print('OK %s  %d -> %d' % (path, len(b), len(t.encode('utf-8'))))



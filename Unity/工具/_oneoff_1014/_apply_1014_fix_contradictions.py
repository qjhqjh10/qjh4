def main():
    byfile = {}
    for path, old, new in P:
        byfile.setdefault(path, []).append((old, new))
    for path, pairs in byfile.items():
        b = io.open(path, 'rb').read()
        assert b.count(b'\r\n') == 0, '%s must be LF' % path
        t = b.decode('utf-8')
        for old, new in pairs:
            n = t.count(old)
            assert n == 1, 'anchor hits=%d in %s :: %r' % (n, path, old[:70])
            t = t.replace(old, new)
        assert '\x00' not in t and '\r\n' not in t
        io.open(path, 'wb').write(t.encode('utf-8'))
        print('OK %s  %d -> %d  (%d 处)' % (path, len(b), len(t.encode('utf-8')), len(pairs)))



#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
gen_arena_scene_anims.py — 13 战场「哪个节点播哪条 clip / 挂哪个 controller」的映射表。

输入（只读）：
  · `d:/2/新解包资源/assets_full/bundle_scenes_scenes_battlearena*/{Animation,Animator}/`
    —— 组件本体（`m_GameObject` / `m_Animations` / `m_Controller`）
  · 同包的 `{AnimationClip,AnimatorController}/*.json` —— **按文件名里的 PathID 解析**
    （`AnimationClip_20.json` → pid 20）；**本包优先，再查 `battlesharedresources`**。
    🔴 踩过的坑：不同包的同名 pid 是**不同对象**（每个场包都有自己的 pid 17/18/19/20）
    ⇒ 先建「本包 pid → 对象」的表，**⛔ 不许拿全库 pid 字典直接查**（会静默取错包）。
  · GameObject/Transform 层级 —— 用 UnityPy 读**真包**（`assets_full` 的 GameObject 文件名
    不含 pid，无法按 pid 反查）。

输出：
  · `d:/4/Unity/数据/游戏数据/arena_scene_anims.json`（全量件 · ✅ 进 git）
  · `d:/4/Unity/MyGame/Assets/CardPresentation/Resources/arena_scene_anims.json`（运行期副本）

判据 → `资料/普查产出_1022/J-A_战场素材与材质诊断.md` §1·4 A1–A3（49 个 Animation 组件没有 clip、
5 个 controller 一个都没进工程）。本表就是「接哪个件」的清单。
"""
import glob
import io
import json
import os

ASSETS = r"d:/2/新解包资源/assets_full"
BUNDLE_DIR = r"d:/2/Warhammer 40k Warpforge/Warpforge_Data/StreamingAssets/aa/StandaloneWindows64"
DST = r"d:/4/Unity/数据/游戏数据/arena_scene_anims.json"
DST_RUNTIME = r"d:/4/Unity/MyGame/Assets/CardPresentation/Resources/arena_scene_anims.json"

SCENE_PREFIX = "bundle_scenes_scenes_"
SHARED_PKG = "bundle_battlesharedresources_assets_all"

# 这些路径由**各自的系统**负责，⛔ 不在本表接第二份（接了两边会抢同一个组件）：
SKIP_PREFIXES = [
    ("BattlePrefab/BattleHud", "BattleHudAnim（战斗线 T01 / A2-B1）"),
    ("BattlePrefab/BattleBoardElements/Cinemachine Vcam", "CameraIntro（相机 intro）"),
]
SKIP_SUFFIXES = [
    ("Card Display Window", "战斗线卡面放大窗（T04）"),
]


def read_json(p):
    return json.load(io.open(p, "r", encoding="utf-8"))


def pid_of(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    return int(stem.rsplit("_", 1)[-1])


def index_pkg(kind, pkg):
    """`{pid: {name, legacy, muscle}}` —— **只扫这一个包**（跨包同 pid 不是同一个对象）。"""
    out = {}
    d = os.path.join(ASSETS, pkg, kind)
    if not os.path.isdir(d):
        return out
    for p in sorted(glob.glob(os.path.join(d, "*.json"))):
        try:
            pid = pid_of(p)
        except Exception:
            continue
        j = read_json(p)
        out[pid] = j
    return out


class Scene(object):
    def __init__(self, arena):
        import UnityPy
        self.arena = arena
        path = os.path.join(BUNDLE_DIR, "scenes_scenes_%s.bundle" % arena)
        env = UnityPy.load(path)
        self.tt = {}
        for o in env.objects:
            try:
                self.tt[o.path_id] = (o.type.name, o.read_typetree())
            except Exception:
                self.tt[o.path_id] = (o.type.name, None)
        t = self.tt
        self.go = {p: d for p, (k, d) in t.items() if k == "GameObject" and isinstance(d, dict)}
        self.tr = {p: d for p, (k, d) in t.items()
                   if k in ("Transform", "RectTransform") and isinstance(d, dict)}
        self.go2tr = {}
        for p, d in self.tr.items():
            self.go2tr.setdefault((d.get("m_GameObject") or {}).get("m_PathID"), []).append(p)

    def chain(self, gopid):
        cur = (self.go2tr.get(gopid) or [None])[0]
        out, guard = [], 0
        while cur and guard < 128:
            d = self.tr[cur]
            g = self.go.get((d.get("m_GameObject") or {}).get("m_PathID"))
            out.append(g.get("m_Name") if g else "?")
            cur = (d.get("m_Father") or {}).get("m_PathID")
            guard += 1
        out.reverse()
        return out


def skip_reason(path):
    for pre, why in SKIP_PREFIXES:
        if path == pre or path.startswith(pre + "/"):
            return why
    for suf, why in SKIP_SUFFIXES:
        if path.endswith("/" + suf) or path == suf:
            return why
    return None


def main():
    arenas = sorted(p[len(SCENE_PREFIX):] for p in (os.path.basename(x) for x in
                    glob.glob(os.path.join(ASSETS, SCENE_PREFIX + "battlearena*")))
                    if os.path.isdir(os.path.join(ASSETS, p)))
    shared_clips = index_pkg("AnimationClip", SHARED_PKG)
    shared_ctrls = index_pkg("AnimatorController", SHARED_PKG)

    doc = {"schema": 1,
           "note": "arena scene anims: which node plays which clip / controller. "
                   "Generated by 工具/gen_arena_scene_anims.py; do not hand-edit.",
           "arenas": []}
    total_anim = total_animator = total_clip = total_ctrl = 0
    unresolved = []
    skipped = []

    for arena in arenas:
        local_clips = index_pkg("AnimationClip", SCENE_PREFIX + arena)
        local_ctrls = index_pkg("AnimatorController", SCENE_PREFIX + arena)
        sc = Scene(arena)
        anims, animators = [], []

        def resolve(pid, local, shared, kind):
            if pid in local:
                return local[pid], "pkg"
            if pid in shared:
                return shared[pid], "shared"
            return None, None

        for pid, (ty, d) in sc.tt.items():
            if ty == "Animation" and isinstance(d, dict):
                gopid = (d.get("m_GameObject") or {}).get("m_PathID")
                path = "/".join(sc.chain(gopid))
                why = skip_reason(path)
                if why:
                    skipped.append([arena, path, why])
                    continue
                refs = []
                for ptr in [d.get("m_Animation")] + list(d.get("m_Animations") or []):
                    if not isinstance(ptr, dict):
                        continue
                    cpid = ptr.get("m_PathID") or 0
                    if not cpid:
                        continue
                    c, where = resolve(cpid, local_clips, shared_clips, "clip")
                    if c is None:
                        unresolved.append(["clip", arena, path, cpid])
                        continue
                    rec = {"name": c.get("m_Name", ""),
                           "legacy": bool(c.get("m_Legacy")),
                           "muscle": int(c.get("m_MuscleClipSize") or 0),
                           "source": where}
                    if rec not in refs:
                        refs.append(rec)
                if not refs:
                    # 原版这里有 `Animation` 但一条 clip 都没引用（`Directional Light`）
                    continue
                anims.append({"path": path,
                              "playAutomatically": bool(d.get("m_PlayAutomatically")),
                              "wrapMode": int(d.get("m_WrapMode") or 0),
                              "clips": refs})
            elif ty == "Animator" and isinstance(d, dict):
                gopid = (d.get("m_GameObject") or {}).get("m_PathID")
                path = "/".join(sc.chain(gopid))
                why = skip_reason(path)
                if why:
                    skipped.append([arena, path, why])
                    continue
                cpid = (d.get("m_Controller") or {}).get("m_PathID") or 0
                if not cpid:
                    continue
                c, where = resolve(cpid, local_ctrls, shared_ctrls, "controller")
                if c is None:
                    unresolved.append(["controller", arena, path, cpid])
                    animators.append({"path": path, "controller": None,
                                      "controllerPid": cpid, "source": None})
                    continue
                animators.append({"path": path, "controller": c.get("m_Name", ""),
                                  "controllerPid": cpid, "source": where})

        doc["arenas"].append({"key": arena, "animations": anims, "animators": animators})
        nc = sum(len(a["clips"]) for a in anims)
        total_anim += len(anims)
        total_animator += len(animators)
        total_clip += nc
        total_ctrl += sum(1 for a in animators if a["controller"])
        print("=== %-28s Animation %d（clip %d）· Animator %d ===" % (arena, len(anims), nc, len(animators)))
        for a in anims:
            print("   A %-58s %s" % (a["path"][:58], [c["name"] for c in a["clips"]]))
        for a in animators:
            print("   N %-58s %s" % (a["path"][:58], a["controller"]))

    doc["summary"] = {"animations": total_anim, "animators": total_animator,
                      "clips": total_clip, "controllers": total_ctrl,
                      "unresolved": len(unresolved), "skipped": len(skipped)}
    body = json.dumps(doc, ensure_ascii=False, indent=1)
    for p in (DST, DST_RUNTIME):
        d = os.path.dirname(p)
        if not os.path.isdir(d):
            os.makedirs(d)
        io.open(p, "w", encoding="utf-8", newline="\n").write(body)
    print("\n[gen] 合计：Animation %d（clip %d）· Animator %d（有 controller %d）· 未解析 %d · 跳过 %d"
          % (total_anim, total_clip, total_animator, total_ctrl, len(unresolved), len(skipped)))
    for u in unresolved:
        print("   MISS %s" % (u,))
    for s in skipped:
        print("   SKIP %s  ← %s" % (s[0] + " | " + s[1], s[2]))
    print("[gen] 写出 %s\n[gen] 运行期副本 %s" % (DST, DST_RUNTIME))


if __name__ == "__main__":
    main()

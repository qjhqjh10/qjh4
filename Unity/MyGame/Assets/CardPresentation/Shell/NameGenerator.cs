        static Dictionary<string, List<char>> _markovChain;
        static System.Random _random;
        static bool _isInitialized;

        /// <summary>原版 `Initialize()`：懒初始化（`new Random()` + `BuildMarkovChain()`），只跑一次。</summary>
        static void Initialize()
        {
            if (_isInitialized) return;
            _isInitialized = true;
            _random = new System.Random();
            BuildMarkovChain();
        }

        /// <summary>原版 `BuildMarkovChain()`：用训练语料建 3 阶链（键 = 3 字、值 = 后继字表）。</summary>
        static void BuildMarkovChain()
        {
            _markovChain = new Dictionary<string, List<char>>();
            for (int n = 0; n < _trainingNames.Length; n++)
            {
                string s = Prefix + (_trainingNames[n] ?? "").ToLower() + Terminator;
                for (int i = 0; i <= s.Length - 4; i++)   // 原版: `Length + -4 < i` 才 break
                {
                    string key = s.Substring(i, 3);
                    char next = s[i + 3];
                    List<char> lst;
                    if (!_markovChain.TryGetValue(key, out lst)) { lst = new List<char>(); _markovChain[key] = lst; }
                    lst.Add(next);
                }
            }
        }

        /// <summary>原版 `GenerateNameOnce()`：从 `"^^^"` 起按 3 阶链逐字生成，直到 `$` 终止符。</summary>
        static string GenerateNameOnce()
        {
            string window = Prefix;
            string result = "";
            while (true)
            {
                List<char> list;
                if (!_markovChain.TryGetValue(window, out list)) return result;
                char chosen;
                if (result.Length < minNameLength)
                {
                    // 数非 '$' 的字（= 还能继续长）
                    int nonDollar = 0;
                    for (int i = 0; i < list.Count; i++) if (list[i] != Terminator) nonDollar++;
                    if (nonDollar < 1)
                    {
                        chosen = list[_random.Next(list.Count)];   // 只有 '$' ⇒ 只能结束
                    }
                    else
                    {
                        int pick = _random.Next(nonDollar);
                        int seen = 0; chosen = Terminator;
                        for (int i = 0; i < list.Count; i++)
                        {
                            if (list[i] == Terminator) continue;
                            if (seen == pick) { chosen = list[i]; break; }
                            seen++;
                        }
                    }
                }
                else
                {
                    chosen = list[_random.Next(list.Count)];       // 长度够 8 ⇒ 可挑任意字（含 '$'）
                }
                if (chosen == Terminator) return result;
                result += chosen;
                window = window.Substring(1) + chosen;
            }
        }

        /// <summary>原版 `GenerateName(int minLength, int maxLength)`：见文件头算法说明。</summary>
        public static string GenerateName(int minLength, int maxLength)
        {
            if (!_isInitialized) Initialize();   // 原版 `GenerateName` 自己也会懒初始化
            int attempts = 0;
            string name;
            while (true)
            {
                name = GenerateNameOnce();
                int len = name.Length;
                if (minLength <= len && len <= maxLength) break;
                attempts++;
                if (attempts > 999)   // 原版: 999 < attempts
                {
                    if (len > maxLength) name = name.Substring(0, maxLength);
                    return CapitalizeFirst(name);
                }
            }
            name = CapitalizeFirst(name);
            // 数字后缀：原版 `if (digitSuffixChance <= NextDouble()) return;` ⇒ 只在 < 概率时追加
            if (_random.NextDouble() < digitSuffixChance)
            {
                int remain = maxLength - name.Length;
                if (remain >= 1)
                {
                    int n = System.Math.Min(2, remain);
                    int count = _random.Next(1, n + 1);   // 原版 `Random.Next(1, n+1)`
                    if (count >= 1)
                    {
                        for (int k = 0; k < count; k++) name += _random.Next(10).ToString();
                    }
                }
            }
            return name;
        }

        static string CapitalizeFirst(string s)
        {
            if (string.IsNullOrEmpty(s)) return s;
            return char.ToUpper(s[0]) + s.Substring(1);
        }

//   · `GenerateName(min,max)`：反复 `GenerateNameOnce` 直到长度落在 [min,max]；1000 次上限后截断到 max。
//     收尾：首字母大写；再按 `digitSuffixChance=0.1` 的概率追加 1..2 位数字（不超过 max）。
//

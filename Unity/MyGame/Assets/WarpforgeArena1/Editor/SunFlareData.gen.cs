    static Dictionary<string, Texture> _tex = new Dictionary<string, Texture>();
    static Texture FlareTex(string file)
    {
        if (_tex.TryGetValue(file, out var t)) return t;
#if UNITY_EDITOR
        t = UnityEditor.AssetDatabase.LoadAssetAtPath<Texture>(TexDir + "/" + file);
        if (t == null) Debug.LogWarning($"[SunFlare] 找不到耀斑贴图 {file}");
#endif
        _tex[file] = t;
        return t;
    }
